import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compactAddButton, button, smallActionButton } from '../../ui/buttons/index.js';
import { repeatedField } from '../../ui/repeated-fields/index.js';
import { links } from '../../ui/links/index.js';

const compact = compactAddButton({ className:'array-row__add', data:'data-repeated-add="phones"', aria:'Добавить телефон' });
assert.match(compact, /class="array-row__add"/);
assert.doesNotMatch(compact, /ui-button/);
assert.match(compact, /data-repeated-add="phones"/);
const phone = repeatedField({label:'Телефон',name:'phones',values:['+79990000000'],type:'tel',addInHeader:true});
assert.match(phone, /class="array-group__header"/);
assert.match(phone, /class="array-row__add"/);
assert.doesNotMatch(phone, /class="ui-button/);
const row = repeatedField({label:'Заметка',name:'notes',addInHeader:false});
assert.match(row, /class="array-row__add"/);
assert.doesNotMatch(row, /class="ui-button/);
const compactLinks = links({ name:'links', compact:true, addInHeader:true });
assert.match(compactLinks, /class="array-row__add"/);
assert.doesNotMatch(compactLinks, /class="ui-button/);
const regularLinks = links({ name:'links',compact:false });
assert.match(regularLinks, /class="ui-links__add"/);
assert.doesNotMatch(regularLinks, /class="ui-button/);
assert.match(button('Сохранить'), /class="ui-button /);
assert.match(smallActionButton({icon:'info'}), /class="small-action-button /);
const css=readFileSync('ui/buttons/buttons.css','utf8');
const inputs=readFileSync('ui/inputs/inputs.css','utf8');
assert.match(css, /\.array-row__add,\.ui-links__add\{display:block;box-sizing:border-box/);
assert.match(inputs, /\.array-group\[data-repeated-add-placement="header"\] \.array-group__header\{display:flex;align-items:center;justify-content:space-between/);
console.log('PASS: compact add controls are independent of full-size buttons');
