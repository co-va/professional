import assert from 'node:assert/strict';
import { inventoryItemCompletion, inventoryManufacturerCompletion, isWeighedInventoryItem, netStocktakeGrams } from '../../core/inventory/completeness.js';
const complete={name:'Кр-11N',manufacturer:'CHI',unit:'г',category:'Краска',sku:'CHI1010',packageQuantity:100,grossWeight:115,tareWeight:15};
assert.equal(isWeighedInventoryItem(complete),true);
assert.equal(inventoryItemCompletion(complete).percentage,100);
assert.equal(inventoryItemCompletion({...complete,tareWeight:null}).complete,false);
assert.ok(inventoryItemCompletion({...complete,tareWeight:null}).missing.includes('Масса тары'));
assert.ok(inventoryItemCompletion({...complete,tareWeight:0}).complete);
assert.equal(inventoryItemCompletion({...complete,grossWeight:10,tareWeight:15}).complete,false);
assert.equal(inventoryItemCompletion({...complete,supplier:''}).percentage,100,'optional supplier does not count');
assert.equal(inventoryManufacturerCompletion([complete,{...complete,tareWeight:null}]).incomplete,1);
assert.ok(inventoryManufacturerCompletion([complete,{...complete,tareWeight:null}]).percentage<100);
assert.equal(netStocktakeGrams({gross:220,containers:3,tareWeight:15}),175);
assert.equal(netStocktakeGrams({gross:45,containers:3,tareWeight:15}),0);
assert.throws(()=>netStocktakeGrams({gross:220,containers:3,tareWeight:null}),/не указана/);
assert.throws(()=>netStocktakeGrams({gross:20,containers:3,tareWeight:15}),/превышает/);
assert.throws(()=>netStocktakeGrams({gross:220,containers:2.5,tareWeight:15}),/количество/);
assert.equal(isWeighedInventoryItem({unit:'шт.'}),false);
assert.equal(isWeighedInventoryItem(null),false,'empty movement row must not crash');
assert.equal(isWeighedInventoryItem(undefined),false,'unselected material must not crash');
console.log('PASS: inventory completeness, zero tare, weighted count formula, no guessed containers');
